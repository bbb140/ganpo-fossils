def main():
    with io.open(SRC, encoding="utf-8") as f:
        recs = json.load(f)

    rows = []
    missing = []
    for r in recs:
        rid = r["记录编号"]
        if rid not in MAP:
            missing.append(rid)
            continue
        cell, group, basis, conf = MAP[rid]
        rows.append([
            rid, r["产地名称"], r["所在市（县）"],
            r["保护分区（大区）"], r["分区小区"],
            r["保护分区（大区）"], cell, OTHER_UNIT.get(rid, "—"), group, basis, conf, "",
        ])

    if missing:
        raise SystemExit("有记录没写进归并表：" + "、".join(missing))
    if len(rows) != len(recs):
        raise SystemExit("行数不一致")

    # 硬校验：12 小区名必须来自 STD，且大区与小区归属自洽
    std2area = {c: a for a, cs in STD.items() for c in cs}
    for row in rows:
        g = row[8]
        if g in ("其它", "未定"):
            continue
        if g not in std2area:
            raise SystemExit("非标准小区名：" + g)
        if std2area[g] != row[5]:
            raise SystemExit("%s 大区/小区冲突：%s / %s" % (row[0], row[5], g))

    with io.open(DST, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(FIELDS)
        w.writerows(rows)

    # 统计
    from collections import Counter
    cnt = Counter(r[8] for r in rows)
    print("已写出：" + DST)
    print("总计 %d 条" % len(rows))
    for area, cells in STD.items():
        line = ["%s %d" % (c, cnt.get(c, 0)) for c in cells]
        print("  %s：%s" % (area, "、".join(line)))
    print("  其它：%d" % cnt.get("其它", 0))
    print("  未定：%d" % cnt.get("未定", 0))
    conf = Counter(r[10] for r in rows)
    print("  置信度：高 %d、中 %d、低 %d" % (conf.get("高", 0), conf.get("中", 0), conf.get("低", 0)))


if __name__ == "__main__":
    main()
